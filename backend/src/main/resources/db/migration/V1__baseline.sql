    id                       VARCHAR(255) NOT NULL PRIMARY KEY,
    owner_id                 BIGINT       NOT NULL,
    business_name            VARCHAR(255) NOT NULL,
    industry                 VARCHAR(255),
    website                  VARCHAR(255),
    location                 VARCHAR(255),
    timezone                 VARCHAR(255),
    working_hours            VARCHAR(255),
    preferred_language       VARCHAR(255),
    call_tone                VARCHAR(255),
    agent_name               VARCHAR(255),
    agent_voice              VARCHAR(255),
    call_objective           TEXT,
    qualification_questions  TEXT,
    agent_guardrails         TEXT,
    objection_playbook       TEXT,
    products_services        TEXT,
    target_audience          TEXT,
    sales_goal               TEXT,
    common_faqs              TEXT,
    pricing_info             TEXT,
    setup_complete           BOOLEAN      NOT NULL,
    created_at               TIMESTAMP(6),
    updated_at               TIMESTAMP(6),
    CONSTRAINT fk_businesses_owner FOREIGN KEY (owner_id) REFERENCES users (id)
);


-- ---------------------------------------------------------------------
-- campaigns
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS campaigns (
    id               VARCHAR(255) NOT NULL PRIMARY KEY,
    owner_id         BIGINT       NOT NULL,
    name             VARCHAR(255) NOT NULL,
    product_service  VARCHAR(255),
    target_audience  VARCHAR(255),
    goal             VARCHAR(255),
    offer            VARCHAR(255),
    channel          VARCHAR(255),
    budget           VARCHAR(255),
    timeline         VARCHAR(255),
    plan             TEXT,
