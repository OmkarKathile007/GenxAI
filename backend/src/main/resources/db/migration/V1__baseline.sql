-- =====================================================================
-- V1 — BASELINE
-- =====================================================================
-- Captures the schema exactly as Hibernate's `ddl-auto=update` left it,
-- so that Flyway can take ownership of the schema from here on.
--
-- IMPORTANT — this script does NOT run against the existing production
-- database. `spring.flyway.baseline-on-migrate=true` with
-- `baseline-version=1` tells Flyway to stamp an already-populated schema
-- as "already at V1" and start applying from V2 onwards. This file only
-- executes on a FRESH database (local dev, CI, a new environment).
--
-- Every statement is written IF NOT EXISTS so that re-running it against
-- a partially-created schema is a no-op rather than a failure.
--
-- Naming follows Spring's default physical naming strategy
-- (camelCase -> snake_case), which is what produced the live schema.
-- =====================================================================


-- ---------------------------------------------------------------------
-- users + roles
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS users (
    id                             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username                       VARCHAR(255) NOT NULL,
    email                          VARCHAR(255) NOT NULL,
    password                       VARCHAR(255) NOT NULL,
    first_login_notification_sent  BOOLEAN,
    CONSTRAINT uk_users_username UNIQUE (username),
    CONSTRAINT uk_users_email    UNIQUE (email)
);

-- @ElementCollection(fetch = EAGER) on User.roles. The element column takes
-- the field name ("roles") under the default naming strategy.
CREATE TABLE IF NOT EXISTS user_roles (
    user_id  BIGINT NOT NULL,
    roles    VARCHAR(255),
    CONSTRAINT fk_user_roles_user FOREIGN KEY (user_id) REFERENCES users (id)
);


-- ---------------------------------------------------------------------
-- businesses
-- ---------------------------------------------------------------------
