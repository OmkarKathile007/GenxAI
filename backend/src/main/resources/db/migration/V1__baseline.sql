    updated_at       TIMESTAMP(6),
    CONSTRAINT fk_campaigns_owner FOREIGN KEY (owner_id) REFERENCES users (id)
);


-- ---------------------------------------------------------------------
-- contacts
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS contacts (
    id              VARCHAR(255) NOT NULL PRIMARY KEY,
    owner_id        BIGINT       NOT NULL,
    full_name       VARCHAR(255) NOT NULL,
    phone           VARCHAR(255) NOT NULL,
    email           VARCHAR(255),
    company         VARCHAR(255),
    source          VARCHAR(255),
    segment         VARCHAR(255),
    status          VARCHAR(255) NOT NULL,
    score           INTEGER,
    notes           TEXT,
    last_called_at  TIMESTAMP(6),
    created_at      TIMESTAMP(6),
    updated_at      TIMESTAMP(6),
    CONSTRAINT fk_contacts_owner FOREIGN KEY (owner_id) REFERENCES users (id)
);


-- ---------------------------------------------------------------------
-- voice_calls
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS voice_calls (
    id             VARCHAR(255) NOT NULL PRIMARY KEY,
    owner_id       BIGINT       NOT NULL,
    contact_id     VARCHAR(255) NOT NULL,
    vapi_call_id   VARCHAR(255),
    type           VARCHAR(255),
    status         VARCHAR(255) NOT NULL,
    transcript     TEXT,
    summary        TEXT,
    recording_url  TEXT,
    ended_reason   VARCHAR(255),
    qualified      BOOLEAN,
    started_at     TIMESTAMP(6),
    ended_at       TIMESTAMP(6),
    created_at     TIMESTAMP(6),
    CONSTRAINT fk_voice_calls_owner   FOREIGN KEY (owner_id)   REFERENCES users (id),
    CONSTRAINT fk_voice_calls_contact FOREIGN KEY (contact_id) REFERENCES contacts (id)
);

CREATE INDEX IF NOT EXISTS idx_voice_calls_vapi_id ON voice_calls (vapi_call_id);


